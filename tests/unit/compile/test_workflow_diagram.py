def test_e4_s08_diagram_only_cli_prints_path(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    """CLI --workflow-diagram-only prints the written diagram path."""
    _scaffold_compile_harness(tmp_path)
    monkeypatch.chdir(tmp_path)
    parser = build_parser()
    args = parser.parse_args(["compile", "example", "--workflow-diagram-only"])
    code = _compile_command(args)
    captured = capsys.readouterr()
    assert code == 0
    assert "Workflow docs refreshed" in captured.out
    assert "workflow-diagram.md" in captured.out
    assert "workflow-paths.md" in captured.out


def test_e4_s08_dry_run_and_diagram_only_conflict(tmp_path: Path) -> None:
    """--dry-run and --workflow-diagram-only are mutually exclusive."""
    _scaffold_compile_harness(tmp_path)
    with pytest.raises(CompileError, match="Cannot combine"):
        run_compile(
            "example",
            project_root=tmp_path,
            dry_run=True,
            workflow_diagram_only=True,
        )

    parser = build_parser()
    with pytest.raises(SystemExit):
        parser.parse_args(
            ["compile", "example", "--dry-run", "--workflow-diagram-only"]
        )
