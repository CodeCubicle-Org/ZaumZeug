def _write_yaml(path: Path, data: dict) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(yaml.safe_dump(data, sort_keys=False), encoding="utf-8")
    return path


def _write_module(agent_dir: Path, *, relative: str, source: str) -> Path:
    path = agent_dir.joinpath(*relative.split("/"))
    path.parent.mkdir(parents=True, exist_ok=True)
    package_root = path.parent
    while package_root != agent_dir and not (package_root / "__init__.py").exists():
        (package_root / "__init__.py").write_text("", encoding="utf-8")
        package_root = package_root.parent
    path.write_text(source, encoding="utf-8")
    return path


def _purge_import(module_name: str) -> None:
    prefix = module_name + "."
    for key in list(sys.modules):
        if key == module_name or key.startswith(prefix):
            del sys.modules[key]


_PLAIN_MODULE = '''\
import dspy

class ResearchModule(dspy.Module):
    def __init__(self):
        super().__init__()
        self.respond = dspy.Predict("question -> answer")

    def forward(self, question: str):
        return dspy.Prediction(answer="harness")
'''

_GOLDEN_EXAMPLE = """\
# Workflow diagram — example

> Auto-generated by `zaumzeug compile example`. Do not edit by hand.

```mermaid
flowchart LR
  s0["researcher\\nmock (mock)"]
```

**Stages:** 1 serial stage · **Entry:** `researcher` · **Generated:** 2026-07-28
"""


def _scaffold_compile_harness(
    project_root: Path,
    *,
    stages: list[dict] | None = None,
    entry: str = "researcher",
    agents: dict[str, dict] | None = None,
) -> Path:
    """Minimal harness with compile.module for full compile tests."""
    harness_dir = project_root / "usr-harnesses" / "example"
    _write_yaml(
        harness_dir / "harness.yaml",
        {"name": "example", "serve": {"hayhooks": {"port": 1416}}},
    )
    stage_list = stages or [{"agent": "researcher"}]
    _write_yaml(
        harness_dir / "workflow.yaml",
        {"entry": entry, "stages": stage_list},
    )

    agent_defs = agents or {
        "researcher": {
            "default_model_id": "mock",
            "models": {
                "mock": {"provider": "mock", "model": "harness-fixture"},
            },
        }
    }
    for agent_name, model_cfg in agent_defs.items():
        agent_dir = harness_dir / "agents" / agent_name
        _write_yaml(
            agent_dir / "agent.yaml",
            {
                "name": agent_name,
                "default_model_id": model_cfg["default_model_id"],
                "agent": {"system_prompt": "prompts/system.md"},
                "compile": {
                    "module": "modules.researcher:ResearchModule",
                    "task_model_id": model_cfg["default_model_id"],
                    "reflection_model_id": model_cfg["default_model_id"],
                    "auto": "light",
                },
            },
        )
        prompt = agent_dir / "prompts" / "system.md"
        prompt.parent.mkdir(parents=True, exist_ok=True)
        prompt.write_text(f"You are {agent_name}.", encoding="utf-8")
        _write_yaml(agent_dir / "agents-models.yaml", model_cfg)
        _write_module(
            agent_dir,
            relative="modules/researcher.py",
            source=_PLAIN_MODULE,
        )
        _purge_import("modules")
    return harness_dir


def test_e4_s08_ac1_compile_writes_diagram(tmp_path: Path) -> None:
    """AC-1: every zaumzeug compile writes docs/workflow-diagram.md (Mermaid)."""
    harness_dir = _scaffold_compile_harness(tmp_path)
    try:
        result = run_compile(
            "example",
            project_root=tmp_path,
            stub_gepa=True,
        )
    finally:
        _purge_import("modules")

    assert result.diagram_path is not None
    assert result.diagram_path == harness_dir / WORKFLOW_DIAGRAM_REL
    assert result.diagram_path.is_file()
    text = result.diagram_path.read_text(encoding="utf-8")
    assert "```mermaid" in text
    assert "flowchart LR" in text


def test_e4_s08_ac2_nodes_include_model_ids(tmp_path: Path) -> None:
    """AC-2: diagram nodes label agent/pipeline id and resolved default_model_id."""
    harness_dir = _scaffold_compile_harness(
        tmp_path,
        stages=[
            {"agent": "researcher"},
            {"agent": "writer"},
            {"pipeline": "summarize"},
        ],
        agents={
            "researcher": {
                "default_model_id": "mock",
                "models": {
                    "mock": {"provider": "mock", "model": "harness-fixture"},
                },
            },
            "writer": {
                "default_model_id": "draft",
                "models": {
                    "draft": {"provider": "openai", "model": "gpt-4o-mini"},
                },
            },
        },
    )
    result = write_workflow_diagram(
        "example",
        project_root=tmp_path,
        generated_on=date(2026, 7, 28),
    )
    text = result.markdown
    assert "researcher" in text
    assert "mock (mock)" in text
    assert "writer" in text
    assert "draft (openai)" in text
    assert "summarize" in text
    assert "s0 --> s1" in text
    assert "s1 --> s2" in text
    assert (harness_dir / WORKFLOW_DIAGRAM_REL).is_file()


def test_e4_s08_ac3_diagram_only_no_gepa(tmp_path: Path) -> None:
    """AC-3: --workflow-diagram-only refreshes diagram without GEPA or LLM calls."""
    harness_dir = _scaffold_compile_harness(tmp_path)

    with patch("zaumzeug.compile.runner.invoke_gepa") as mocked_gepa:
        result = run_compile(
            "example",
            project_root=tmp_path,
            workflow_diagram_only=True,
        )

    mocked_gepa.assert_not_called()
    assert result.workflow_diagram_only is True
    assert result.agents == []
    assert result.diagram_path is not None
    assert result.diagram_path.is_file()
    assert "```mermaid" in result.diagram_path.read_text(encoding="utf-8")
    assert not (harness_dir / "agents" / "researcher" / "artifacts").exists()

    parser = build_parser()
    args = parser.parse_args(["compile", "example", "--workflow-diagram-only"])
    assert args.workflow_diagram_only is True
    assert args.dry_run is False


