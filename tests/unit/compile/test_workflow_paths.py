def _scaffold_compile_harness(
    project_root: Path,
    *,
    stages: list[dict] | None = None,
    entry: str = "researcher",
    agents: dict[str, dict] | None = None,
    agent_tools: dict[str, dict] | None = None,
) -> Path:
    harness_dir = project_root / "usr-harnesses" / "example"
    _write_yaml(
        harness_dir / "harness.yaml",
        {"name": "example", "serve": {"hayhooks": {"port": 1416}}},
    )
    stage_list = stages or [{"agent": "researcher"}]
    _write_yaml(
        harness_dir / "workflow.yaml",
        {"entry": entry, "stages": stage_list},
    )

    agent_defs = agents or {
        "researcher": {
            "default_model_id": "mock",
            "models": {
                "mock": {"provider": "mock", "model": "harness-fixture"},
            },
        }
    }
    tools_by_agent = agent_tools or {}
    for agent_name, model_cfg in agent_defs.items():
        agent_dir = harness_dir / "agents" / agent_name
        agent_body: dict = {
            "name": agent_name,
            "default_model_id": model_cfg["default_model_id"],
            "agent": {"system_prompt": "prompts/system.md"},
            "compile": {
                "module": "modules.researcher:ResearchModule",
                "task_model_id": model_cfg["default_model_id"],
                "reflection_model_id": model_cfg["default_model_id"],
                "auto": "light",
            },
        }
        if agent_name in tools_by_agent:
            agent_body["tools"] = tools_by_agent[agent_name]
        _write_yaml(agent_dir / "agent.yaml", agent_body)
        prompt = agent_dir / "prompts" / "system.md"
        prompt.parent.mkdir(parents=True, exist_ok=True)
        prompt.write_text(f"You are {agent_name}.", encoding="utf-8")
        _write_yaml(agent_dir / "agents-models.yaml", model_cfg)
        _write_module(
            agent_dir,
            relative="modules/researcher.py",
            source=_PLAIN_MODULE,
        )
        _purge_import("modules")
    return harness_dir


def test_e4_s09_ac1_compile_writes_paths_md(tmp_path: Path) -> None:
    harness_dir = _scaffold_compile_harness(
        tmp_path,
        agent_tools={"researcher": {"builtin": ["web_fetch"]}},
    )
    try:
        result = run_compile("example", project_root=tmp_path, stub_gepa=True)
    finally:
        _purge_import("modules")

    assert result.paths_path is not None
    assert result.paths_path == harness_dir / WORKFLOW_PATHS_REL
    assert result.paths_path.is_file()
    text = result.paths_path.read_text(encoding="utf-8")
    assert "```mermaid" in text
    assert "flowchart LR" in text


